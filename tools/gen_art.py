"""Draws the Candy Kingdom obstacles, the two crowns and Prismo's portal.

Original art, generated by code: flat cartoon colors with thick dark outlines, to sit next to the
Lich sheet. Everything is drawn at 4x and downsampled for clean edges.

    python tools/gen_art.py                      # writes public/assets/images/*.png
    python tools/gen_art.py --preview art.png    # also writes a contact sheet

Needs Pillow and numpy. Output sizes follow docs/assets.md: the game scales each sprite to a height
set by the renderer, so only the aspect ratio and the anchor matter. Obstacles are cropped to the
ground line (bottom anchor), crowns and the portal are centered.
"""

import argparse
import math
import os
import random

import numpy as np
from PIL import Image, ImageDraw, ImageFont

SS = 4
OUTLINE = (29, 22, 48, 255)


def hexc(h, a=255):
    return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), a)


class Canvas:
    """A transparent canvas drawn at SS times its size. Coordinates are in output pixels."""

    def __init__(self, w, h):
        self.w, self.h = w, h
        self.im = Image.new("RGBA", (w * SS, h * SS), (0, 0, 0, 0))
        self.d = ImageDraw.Draw(self.im)

    @staticmethod
    def _p(pts):
        return [(x * SS, y * SS) for x, y in pts]

    def poly(self, pts, fill, outline=OUTLINE, width=4):
        p = self._p(pts)
        if fill is not None:
            self.d.polygon(p, fill=fill)
        if outline:
            self.d.line(p + [p[0]], fill=outline, width=int(width * SS), joint="curve")

    def ellipse(self, cx, cy, rx, ry, fill, outline=None, width=4):
        box = [(cx - rx) * SS, (cy - ry) * SS, (cx + rx) * SS, (cy + ry) * SS]
        self.d.ellipse(box, fill=fill, outline=outline, width=int(width * SS))

    def line(self, pts, fill, width):
        p = self._p(pts)
        self.d.line(p, fill=fill, width=int(width * SS), joint="curve")
        r = width * SS / 2
        for x, y in (p[0], p[-1]):
            self.d.ellipse([x - r, y - r, x + r, y + r], fill=fill)

    def done(self):
        return self.im.resize((self.w, self.h), Image.LANCZOS)


def arc(cx, cy, r, a0, a1, n=48):
    return [(cx + r * math.cos(a0 + (a1 - a0) * i / n), cy + r * math.sin(a0 + (a1 - a0) * i / n)) for i in range(n + 1)]


# ------------------------------------------------------------------ obstacles


def gumdrop():
    """Low sugared gumdrop you jump over. Drawn 9u tall."""
    W, H = 260, 216
    c = Canvas(W, H)
    cx, base, rx, ry = W / 2, H - 14, 118, 186
    def dome(rx_, ry_, dx=0.0, dy=0.0, bottom=10):
        top = [(cx + dx - rx_ * math.cos(t), base + dy - ry_ * math.sin(t)) for t in [math.pi * i / 60 for i in range(61)]]
        low = [(cx + dx + rx_ * math.cos(t), base + dy + bottom * math.sin(t)) for t in [math.pi * i / 20 for i in range(21)]]
        return top + low
    shell = dome(rx, ry)
    c.poly(shell, hexc("#2fb257"), None)
    c.poly(dome(rx * 0.93, ry * 0.9, -rx * 0.07, -ry * 0.05, 4), hexc("#3fd16a"), None)
    c.poly(shell, None, OUTLINE, 6)
    c.ellipse(cx - rx * 0.38, base - ry * 0.62, 26, 38, (255, 255, 255, 150))
    rnd = random.Random(7)
    for _ in range(46):
        x = rnd.uniform(-0.9, 0.9) * rx
        y = rnd.uniform(0.05, 0.95) * ry
        if (x / rx) ** 2 + (y / ry) ** 2 < 0.8:
            s = rnd.uniform(3, 5.5)
            c.ellipse(cx + x, base - y, s, s, (255, 255, 255, 215))
    return c.done()


def candy_cane():
    """Tall red and white candy cane. Drawn 18u tall."""
    W, H = 232, 432
    c = Canvas(W, H)
    pw = 46
    px = 76
    top_y = 122
    hook = arc(px + 66, top_y, 66, math.pi, 2 * math.pi + 0.42)
    path = [(px, H - 32), (px, top_y)] + hook[1:]
    # dark outline, then the striped body, masked to the same path
    c.line(path, OUTLINE, pw + 14)
    body = Canvas(W, H)
    body.line(path, (255, 255, 255, 255), pw)
    mask = body.im.split()[3]
    stripes = Image.new("RGBA", body.im.size, hexc("#fffaf5"))
    sd = ImageDraw.Draw(stripes)
    step = 60 * SS
    for k in range(-4, 16):
        x0 = k * step
        sd.polygon([(x0, 0), (x0 + step / 2, 0), (x0 + step / 2 - 120 * SS, H * SS), (x0 - 120 * SS, H * SS)], fill=hexc("#e8213f"))
    c.im.paste(stripes, (0, 0), mask)
    c.line([(px - 13, H - 60), (px - 13, top_y + 4)], (255, 255, 255, 120), 7)
    return c.done()


def licorice_arch():
    """A gate of licorice you slide under. Drawn 14u tall, clear space below the bar."""
    W, H = 980, 336
    c = Canvas(W, H)
    black, hi = hexc("#1f1426"), hexc("#4a3558")
    post_w, bar_t = 64, 76
    def rope(x0, y0, x1, y1, w_):
        c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], black, OUTLINE, 6)
    # posts
    rope(34, 110, 34 + post_w, H - 8, post_w)
    rope(W - 34 - post_w, 110, W - 34, H - 8, post_w)
    # lintel with a slight upward bow
    lt = [(24, 70 + bar_t / 2)] + [(24 + (W - 48) * i / 40, 70 - 22 * math.sin(math.pi * i / 40)) for i in range(41)] + [(W - 24, 70 + bar_t / 2)]
    lb = [(W - 24, 70 + bar_t / 2 + 14)] + [(24 + (W - 48) * (40 - i) / 40, 70 + bar_t - 22 * math.sin(math.pi * i / 40)) for i in range(41)] + [(24, 70 + bar_t / 2 + 14)]
    c.poly(lt + lb, black, OUTLINE, 6)
    # licorice twist lines on posts and bar, and a pink stripe along the bar
    for x0 in (34, W - 34 - post_w):
        for y in range(130, H - 20, 34):
            c.line([(x0 + 10, y + 16), (x0 + post_w - 10, y)], hi, 6)
    for x in range(48, W - 60, 40):
        yb = 70 - 22 * math.sin(math.pi * (x - 24) / (W - 48))
        c.line([(x, yb + 12), (x + 22, yb + bar_t - 14)], hi, 6)
    pink = [(24 + (W - 48) * i / 40, 70 + bar_t - 12 - 22 * math.sin(math.pi * i / 40)) for i in range(41)]
    c.line(pink, hexc("#ff5d8f"), 8)
    return c.done()


# --------------------------------------------------------------------- crowns


GOLD, GOLD_DARK = hexc("#f6c945"), hexc("#d9a21b")


def gem(c, cx, cy, rx, ry, fill, rim):
    c.ellipse(cx, cy, rx, ry, rim, OUTLINE, 5)
    c.ellipse(cx, cy, rx * 0.78, ry * 0.78, fill)
    c.ellipse(cx - rx * 0.3, cy - ry * 0.32, rx * 0.22, ry * 0.26, (255, 255, 255, 190))


def tiara():
    """Princess Bubblegum's tiara: gold band, one large blue gem. Drawn 6u tall."""
    W, H = 320, 240
    c = Canvas(W, H)
    shape = [(28, 206), (28, 150), (96, 168), (160, 64), (224, 168), (292, 150), (292, 206)]
    c.poly(shape, GOLD_DARK, None)
    c.poly([(28, 186), (28, 150), (96, 168), (160, 64), (224, 168), (292, 150), (292, 186)], GOLD, None)
    c.poly(shape, None, OUTLINE, 6)
    for x, y in ((28, 150), (292, 150)):
        c.ellipse(x, y, 14, 14, GOLD, OUTLINE, 5)
    c.ellipse(160, 60, 15, 15, GOLD, OUTLINE, 5)
    gem(c, 160, 138, 34, 40, hexc("#3aa0ff"), hexc("#1d62b8"))
    return c.done()


def ice_king_crown():
    """The Ice King's crown: gold, three large red rubies. Drawn 6u tall (and 1.3x in play)."""
    W, H = 320, 240
    c = Canvas(W, H)
    shape = [(28, 208), (28, 96), (96, 150), (160, 40), (224, 150), (292, 96), (292, 208)]
    c.poly(shape, GOLD_DARK, None)
    c.poly([(28, 188), (28, 96), (96, 150), (160, 40), (224, 150), (292, 96), (292, 188)], GOLD, None)
    c.poly(shape, None, OUTLINE, 6)
    for x, y in ((28, 96), (160, 36), (292, 96)):
        c.ellipse(x, y, 14, 14, GOLD, OUTLINE, 5)
    for x in (82, 160, 238):
        gem(c, x, 172, 27, 31, hexc("#ff2d55"), hexc("#a3122f"))
    return c.done()


# --------------------------------------------------------------------- portal

PORTAL_FRAMES, PORTAL_PX = 24, 256


def portal_frame(i):
    S = PORTAL_PX
    R = S * 0.4545  # the glow is ~0.91 of the sprite height; the game draws it at 2.2x its radius
    yy, xx = np.mgrid[0:S, 0:S]
    d = np.hypot(xx - S / 2 + 0.5, yy - S / 2 + 0.5) / R
    inner, mid, outer = np.array([255, 255, 255.0]), np.array([179, 136, 255.0]), np.array([120, 60, 220.0])
    t1 = np.clip(d / 0.6, 0, 1)[..., None]
    t2 = np.clip((d - 0.6) / 0.4, 0, 1)[..., None]
    rgb = np.where(d[..., None] < 0.6, inner + (mid - inner) * t1, mid + (outer - mid) * t2)
    alpha = np.interp(d, [0, 0.6, 1.0, 1.04], [0.95, 0.7, 0.12, 0.0])
    img = np.dstack([rgb, alpha * 255]).astype(np.uint8)
    base = Image.fromarray(img, "RGBA")
    c = Canvas(S, S)
    c.im = base.resize((S * SS, S * SS), Image.BICUBIC)
    c.d = ImageDraw.Draw(c.im)
    t = i / PORTAL_FRAMES
    # three spiral arms: 3-fold symmetric, turning 120 degrees over the loop so it repeats exactly
    spin = t * (2 * math.pi / 3)
    for arm in range(3):
        a0 = spin + arm * 2 * math.pi / 3
        pts = [(S / 2 + R * 0.92 * (k / 40) * math.cos(a0 + 3.2 * (k / 40)), S / 2 + R * 0.92 * (k / 40) * math.sin(a0 + 3.2 * (k / 40))) for k in range(41)]
        c.line(pts, (255, 255, 255, 120), 7)
    # three rings, whole turns per loop so it repeats exactly
    for ring, (k, col) in enumerate(((1, "#d1b3ff"), (-1, "#ffe66d"), (2, "#d1b3ff"))):
        r = R * (1 - ring * 0.2)
        a = t * k * 2 * math.pi + ring * 2
        c.line(arc(S / 2, S / 2, r, a, a + math.pi * 1.2), hexc(col), R * 0.12)
    return c.done()


def portal_sheet():
    sheet = Image.new("RGBA", (PORTAL_PX * PORTAL_FRAMES, PORTAL_PX), (0, 0, 0, 0))
    for i in range(PORTAL_FRAMES):
        sheet.alpha_composite(portal_frame(i), (i * PORTAL_PX, 0))
    return sheet


# -------------------------------------------------------------------- driver

ASSETS = {
    "gumdrop.png": gumdrop,
    "candy-cane.png": candy_cane,
    "licorice-arch.png": licorice_arch,
    "tiara-bubblegum.png": tiara,
    "crown-ice-king.png": ice_king_crown,
    "portal.png": portal_sheet,
}


def contact_sheet(images, path):
    """Everything on a road-colored background with labels, for a quick look."""
    pad, label_h = 36, 28
    scaled = []
    for name, im in images.items():
        if name == "portal.png":
            im = im.crop((0, 0, PORTAL_PX, PORTAL_PX))
        k = 300 / im.height if im.height > 300 else 1.0
        scaled.append((name, im.resize((max(1, int(im.width * k)), max(1, int(im.height * k))), Image.LANCZOS)))
    W = max(1400, sum(i.width for _, i in scaled[:3]) + pad * 4)
    rows = [scaled[:3], scaled[3:]]
    H = sum(max(i.height for _, i in r) + label_h + pad for r in rows) + pad
    sheet = Image.new("RGBA", (W, H), hexc("#8d6fb3"))
    d = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.truetype("arial.ttf", 20)
    except OSError:
        font = ImageFont.load_default()
    y = pad
    for r in rows:
        x = pad
        rh = max(i.height for _, i in r)
        for name, im in r:
            sheet.alpha_composite(im, (x, y + rh - im.height))
            d.text((x, y + rh + 4), name, fill=(255, 255, 255, 255), font=font)
            x += im.width + pad
        y += rh + label_h + pad
    sheet.convert("RGB").save(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default=os.path.join("public", "assets", "images"))
    ap.add_argument("--preview", help="write a contact sheet PNG here")
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    images = {}
    for name, fn in ASSETS.items():
        im = fn()
        im.save(os.path.join(args.out_dir, name), optimize=True)
        images[name] = im
        print(f"{name}: {im.width}x{im.height}")
    if args.preview:
        contact_sheet(images, args.preview)
        print("preview ->", args.preview)


if __name__ == "__main__":
    main()
